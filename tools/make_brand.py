#!/usr/bin/env python3
"""Draws the Switch build's homebrew icon and loading-screen logo (sheroes-nx's own: plain text, no game art).

  python3 tools/make_brand.py [--font <ttf>]

Writes switch/icon.jpg (256x256, the homebrew menu icon) and src/sheroes_logo.h (640x128, the loading screen logo, in
the run-length layout switch_nx.c reads: runs of (count, r, g, b), rows from the top).
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

BG = (10, 6, 12)
FG = (196, 172, 120)
DIM = (120, 40, 40)


def font(path, size):
    try:
        return ImageFont.truetype(path, size)
    except OSError:
        return ImageFont.load_default()


def centered(draw, y, text, f, fill, width):
    w = draw.textlength(text, font=f)
    draw.text(((width - w) / 2, y), text, font=f, fill=fill)


def icon(path, ttf):
    im = Image.new("RGB", (256, 256), BG)
    d = ImageDraw.Draw(im)
    d.rectangle((8, 8, 247, 247), outline=DIM, width=4)
    centered(d, 66, "SONIC", font(ttf, 48), FG, 256)
    centered(d, 128, "HEROES", font(ttf, 40), FG, 256)
    centered(d, 204, "Xbox recomp", font(ttf, 20), DIM, 256)
    im.save(path, quality=92)


def logo(path, ttf):
    w, h = 640, 128
    im = Image.new("RGB", (w, h), BG)
    d = ImageDraw.Draw(im)
    centered(d, 18, "SONIC HEROES", font(ttf, 56), FG, w)
    centered(d, 88, "sheroes-nx", font(ttf, 22), DIM, w)
    px = [im.getpixel((x, y)) for y in range(h) for x in range(w)]
    runs = []
    i = 0
    while i < len(px):
        n = 1
        while i + n < len(px) and n < 255 and px[i + n] == px[i]:
            n += 1
        runs.append((n,) + px[i])
        i += n
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_brand.py (sheroes-nx's own text logo). Do not edit. */\n")
        f.write("#define NFSU2_LOGO_W %d\n#define NFSU2_LOGO_H %d\n" % (w, h))
        f.write("#define NFSU2_LOGO_BG_R %d\n#define NFSU2_LOGO_BG_G %d\n#define NFSU2_LOGO_BG_B %d\n" % BG)
        f.write("/* runs of (count, r, g, b), row-major from the top */\n")
        f.write("static const unsigned char k_nfsu2_logo_rle[%d] = {\n" % (len(runs) * 4))
        for k in range(0, len(runs), 6):
            f.write("    " + "".join("%d,%d,%d,%d," % r for r in runs[k:k + 6]) + "\n")
        f.write("};\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf")
    a = ap.parse_args()
    icon(os.path.join(root, "switch", "icon.jpg"), a.font)
    logo(os.path.join(root, "src", "sheroes_logo.h"), a.font)


if __name__ == "__main__":
    main()
